// Сокращение текста для методички — работает без интернета, только по правилам ниже.
// Смысл и оговорки сохраняются: «может привести» → «может →», «маловероятно» не превращается в «вероятно».
(function (root) {
    const L = '\\p{L}';
    // Слово целиком: не часть другого слова (\b в JS не работает с кириллицей).
    const word = (body) => new RegExp(`(?<![${L}\\d])(?:${body})(?![${L}])`, 'giu');

    // [шаблон, замена, группа]. Группы включаются галочками в интерфейсе.
    const RULES = [
        // --- Вероятность ---
        ['с\\s+(?:большой|высокой|наибольшей|значительной)\\s+(?:долей\\s+)?вероятност(?:ью|и)', 'вероятно', 'prob'],
        ['по\\s+всей\\s+(?:видимости|вероятности)', 'вероятно', 'prob'],
        ['скорее\\s+всего', 'вероятно', 'prob'],
        ['с\\s+(?:малой|низкой|небольшой)\\s+вероятностью', 'маловероятно', 'prob'],
        ['есть\\s+вероятность,?\\s+что', 'вероятно,', 'prob'],

        // --- Связки и вводные слова ---
        ['(?:следует|стоит|важно|необходимо|нужно|хочется|хотелось\\s+бы)\\s+(?:отметить|подчеркнуть|сказать|заметить),?\\s+что', '', 'filler'],
        ['дело\\s+в\\s+том,?\\s+что', '', 'filler'],
        ['на\\s+самом\\s+деле', '', 'filler'],
        ['по\\s+сути(?:\\s+дела)?', '', 'filler'],
        ['в\\s+принципе', '', 'filler'],
        ['в\\s+целом', '', 'filler'],
        ['так\\s+или\\s+иначе', '', 'filler'],
        ['фактически', '', 'filler'],
        ['так\\s+называем(?:ый|ая|ое|ые|ого|ой|ому|ым|ых|ую|ыми)', '', 'filler'],
        ['как\\s+правило', 'обычно', 'filler'],
        ['в\\s+большинстве\\s+случаев', 'чаще', 'filler'],
        ['в\\s+(?:ряде|некоторых)\\s+случаев|в\\s+некоторых\\s+случаях', 'иногда', 'filler'],
        ['(?:достаточно|довольно|очень)\\s+часто', 'часто', 'filler'],
        ['(?:очень|крайне|особенно|чрезвычайно)\\s+важно', '❗ важно', 'filler'],
        ['для\\s+того,?\\s+чтобы', 'чтобы', 'filler'],
        ['в\\s+связи\\s+с\\s+тем,?\\s+что|из-за\\s+того,?\\s+что|по\\s+причине\\s+того,?\\s+что|ввиду\\s+того,?\\s+что|так\\s+как', 'т.к.', 'filler'],
        ['необходимо', 'нужно', 'filler'],

        // --- Сокращения ---
        ['в\\s+том\\s+числе', 'в т.ч.', 'abbr'],
        ['и\\s+так\\s+далее|и\\s+т\\.\\s?д\\.', 'и т.д.', 'abbr'],
        ['то\\s+есть', 'т.е.', 'abbr'],
        ['например', 'напр.', 'abbr'],
        ['количеств(?:о|а|у|ом|е)', 'кол-во', 'abbr'],
        ['(?:может|могут)\\s+(?:привести|приводить)\\s+к(?:о)?', 'может →', 'abbr'],
        ['(?:приводит|приводят)\\s+к(?:о)?', '→', 'abbr'],
        ['(?:не\\s+более|не\\s+больше)(?=\\s*\\d)', '≤', 'abbr'],
        ['(?:не\\s+менее|не\\s+меньше)(?=\\s*\\d)', '≥', 'abbr'],
        ['(?:более|больше)(?:\\s+чем)?(?=\\s*\\d)', '>', 'abbr'],
        ['(?:менее|меньше)(?:\\s+чем)?(?=\\s*\\d)', '<', 'abbr'],
        ['(?:примерно|приблизительно|около|порядка)(?=\\s*\\d)', '≈', 'abbr'],

        // --- Стрелки ⬆️ ---
        ['выше\\s+нормы', '⬆️ нормы', 'arrows'],
        ['рост(?:а|у|ом|е)?(?!\\s*[:\\-—–]?\\s*\\d)', '⬆️', 'arrows'], // «рост 186 см» не трогаем
        ['прирост(?:а|у|ом|е)?', '⬆️', 'arrows'],
        ['(?:повышени|увеличени|подняти|возрастани)(?:е|я|ю|ем|и)', '⬆️', 'arrows'],
        ['подъ[её]м(?:а|у|ом|е)?', '⬆️', 'arrows'],
        ['(?:повыша|увеличива|поднима|возраста)(?:ет|ют|ется|ются|ть|ться|л|ла|ло|ли|лся|лась|лись)', '⬆️', 'arrows'],
        ['(?:повыс|увелич)(?:ить|иться|ил|ила|ило|или|ился|илась|ились|ится|ятся|ит|ят)', '⬆️', 'arrows'],
        ['(?:повышен|увеличен)(?:а|о|ы)?', '⬆️', 'arrows'],
        ['(?:повышенн|увеличенн)(?:ый|ая|ое|ые|ого|ой|ому|ым|ых|ую|ыми|ом)', '⬆️', 'arrows'],
        ['раст(?:[её]т|ут)|вырос(?:ла|ло|ли)?|поднял(?:ся|ась|ось|ись|а|о|и)?', '⬆️', 'arrows'],

        // --- Стрелки ⬇️ ---
        ['ниже\\s+нормы', '⬇️ нормы', 'arrows'],
        ['(?:снижени|понижени|уменьшени|падени|убывани)(?:е|я|ю|ем|и)', '⬇️', 'arrows'],
        ['спад(?:а|у|ом|е)?', '⬇️', 'arrows'],
        ['(?:снижа|понижа|уменьша|убыва)(?:ет|ют|ется|ются|ть|ться|л|ла|ло|ли|лся|лась|лись)', '⬇️', 'arrows'],
        ['(?:сниз|пониз|уменьш)(?:ить|иться|ил|ила|ило|или|ился|илась|ились|ится|ятся|ит|ят)', '⬇️', 'arrows'],
        ['(?:снижен|понижен|уменьшен)(?:а|о|ы)?', '⬇️', 'arrows'],
        ['(?:сниженн|пониженн|уменьшенн)(?:ый|ая|ое|ые|ого|ой|ому|ым|ых|ую|ыми|ом)', '⬇️', 'arrows'],
        ['пада(?:ет|ют)|упал(?:а|о|и)?', '⬇️', 'arrows'],
    ];
    const COMPILED = RULES.map(([pat, rep, group]) => ({ re: word(pat), rep, group }));

    // Свои замены: строки «что = на что». Слева можно писать несколько вариантов через «|».
    function parseCustom(text) {
        const out = [];
        for (const raw of String(text || '').split('\n')) {
            const line = raw.trim();
            if (!line || line.startsWith('#')) continue;
            const m = line.match(/^(.+?)\s*(?:=|→|->)\s*(.*)$/);
            if (!m) continue;
            const alts = m[1].split('|').map((s) => s.trim()).filter(Boolean)
                .map((s) => s.replace(/[.*+?^${}()[\]\\]/g, '\\$&').replace(/\s+/g, '\\s+'));
            if (alts.length) out.push({ re: word(alts.join('|')), rep: m[2].trim(), group: 'custom' });
        }
        return out;
    }

    function matchCase(src, rep) {
        if (!rep) return rep;
        const first = src.charAt(0);
        const isUpper = first !== first.toLowerCase() && first === first.toUpperCase();
        return isUpper && /\p{Ll}/u.test(rep.charAt(0)) ? rep.charAt(0).toUpperCase() + rep.slice(1) : rep;
    }

    const CUT = '\u0001'; // метка на месте удалённой связки
    function tidy(text) {
        return text
            .split('\n')
            .map((line) => line
                // если связку убрали в начале предложения — следующее слово с заглавной
                .replace(new RegExp(`(^|[.!?…]\\s*)${CUT}[\\s,]*(\\p{Ll})`, 'gu'), (m, a, b) => (a ? a.trimEnd() + ' ' : '') + b.toUpperCase())
                .split(CUT).join('')
                // «…, обычно, …» → «… обычно …»
                .replace(/,\s*(обычно|вероятно|чаще|иногда)\s*,/gu, ' $1')
                .replace(/[ \t]{2,}/g, ' ')
                .replace(/\s+([,.;:!?)])/g, '$1')
                .replace(/([(«])\s+/g, '$1')
                .replace(/,\s*,+/g, ',')
                .replace(/^\s*[,;:]\s*/, '')
                .replace(/([.!?…])\s*,\s*/g, '$1 ')
                .trim())
            .join('\n')
            .replace(/\n{3,}/g, '\n\n')
            .trim();
    }

    function shorten(text, opts = {}) {
        const groups = { prob: true, filler: true, abbr: true, arrows: true, ...opts.groups };
        const rules = [...parseCustom(opts.custom), ...COMPILED.filter((r) => groups[r.group])];
        let out = String(text || '');
        let count = 0;
        for (const { re, rep } of rules) {
            out = out.replace(re, (m) => { count++; return rep ? matchCase(m, rep) : CUT; });
        }
        // «⬆️ ⬆️» после двойной замены и стрелка перед запятой
        out = out.replace(/(⬆️|⬇️)(\s+\1)+/g, '$1');
        out = tidy(out);
        return { text: out, replacements: count };
    }

    root.Shorten = { shorten, parseCustom, RULES };
    if (typeof module !== 'undefined') module.exports = root.Shorten;
})(typeof window !== 'undefined' ? window : globalThis);
